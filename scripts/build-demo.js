#!/usr/bin/env node
/* Builds docs/demo.html: the real app, running on a made-up sample edition, for the live demo on the homepage.
   It is generated from www/index.html, so it never goes stale. Run it after changing www/index.html
   (the editor hook in .claude/settings.json does this for you):  node scripts/build-demo.js */
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'www/index.html'), 'utf8');
const content = require('./demo-content.js');
const ver = (app.match(/const APP_VERSION='([^']+)'/) || [])[1] || '';
if (!ver) { console.error('build-demo: could not find APP_VERSION'); process.exit(1); }
const tipKeys = ((app.match(/const TIPQ=\[(.*?)\];/s) || [])[1] || '').match(/\['(\w+)',\d+,/g) || [];
const content2 = Object.assign({ ver, tipKeys: tipKeys.map(x => x.slice(2, x.indexOf("'", 2))) }, content);
const shim = fs.readFileSync(path.join(__dirname, 'demo-shim.js'), 'utf8')
  .replace('/*DATA*/null', JSON.stringify(content2).replace(/</g, '\\u003c'));
const csp = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline' 'self'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self' data: blob:; media-src 'self' data: blob:; worker-src blob:; object-src 'none'; frame-src 'none'; form-action 'none'; base-uri 'self'";
/* Fonts travel inside the page: the demo runs in a sandboxed frame that cannot load files from the site as fonts. Only the faces the app uses most are included. */
const fontCss = (() => {
  const css = fs.readFileSync(path.join(root, 'docs/fonts.css'), 'utf8');
  const faces = css.match(/@font-face\s*\{[^}]*\}/g) || [];
  const keep = faces.filter(f => /Cormorant Garamond/.test(f) || (/'Inter'/.test(f) && /inter-56724408/.test(f)));
  /* one face per font file, covering the weight range, so each file is embedded once */
  const groups = new Map();
  keep.forEach(f => {
    const fam = (f.match(/font-family:\s*([^;]+);/) || [])[1], sty = (f.match(/font-style:\s*([^;]+);/) || [])[1] || 'normal';
    const wt = +((f.match(/font-weight:\s*(\d+)/) || [])[1] || 400), file = (f.match(/url\(fonts\/([^)]+)\)/) || [])[1];
    const k = fam + '|' + sty + '|' + file;
    const g = groups.get(k) || { fam, sty, file, lo: wt, hi: wt, range: (f.match(/unicode-range:\s*([^;]+);/) || [])[1] };
    g.lo = Math.min(g.lo, wt); g.hi = Math.max(g.hi, wt); groups.set(k, g);
  });
  return [...groups.values()].map(g => '@font-face{font-family:' + g.fam + ';font-style:' + g.sty + ';font-weight:' + g.lo + ' ' + g.hi + ';font-display:swap;src:url(data:font/woff2;base64,' + fs.readFileSync(path.join(root, 'docs/fonts', g.file)).toString('base64') + ') format(\'woff2\')' + (g.range ? ';unicode-range:' + g.range : '') + '}').join('\n');
})();
const inject =
  '<meta http-equiv="Content-Security-Policy" content="' + csp + '">' +
  '<!-- GENERATED by scripts/build-demo.js from www/index.html. Do not edit by hand. -->' +
  '<meta name="robots" content="noindex,nofollow">' +
  '<base href="/app/">' +
  '<style>' + fontCss + '</style>' +
  '<style>html.demo #add,html.demo #gear{display:none!important}</style>' +
  '<script>' + shim + '</script>';
const m = app.match(/<head[^>]*>/);
if (!m) { console.error('build-demo: no <head> found'); process.exit(1); }
/* the demo keeps only its own, stricter policy (above), not the app's */
let out = app.replace(/<!-- E2 Content Security Policy[\s\S]*?-->\s*/, '').replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\s*/, '').replace(/<title>[^<]*<\/title>/, '<title>CyPress Reader demo (made-up sample stories)</title>').replace(m[0], m[0] + inject);
/* the app's own manifest, icons and service worker are not wanted in the demo */
out = out.replace(/<link rel="manifest"[^>]*>/g, '');
fs.writeFileSync(path.join(root, 'docs/demo.html'), out);
console.log('docs/demo.html written (app version ' + ver + ', ' + Math.round(out.length / 1024) + ' KB)');
